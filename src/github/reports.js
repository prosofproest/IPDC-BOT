import PDFDocument from 'pdfkit';
import { createLogger } from '../utils/logger.js';
import { dayKeyIST, fmtIST, mapLimit } from '../utils/misc.js';
import { LOGO_PATH } from '../ui.js';
import { Activity } from './activity.js';

const log = createLogger('reports');
const DAY = 86400000;
// pdfkit core fonts are Latin-1 only: replace anything else instead of emitting garbage.
const latin = (s) => String(s ?? '').replace(/[^\x20-\x7E\xA0-\xFF]/g, '?');

/** One consolidated PDF per PM team for the 24h window ending at `untilMs`. */
export async function buildPmReportPdf({ pm, data, names, details, summary, untilMs, sinceMs }) {
  const doc = new PDFDocument({ size: 'A4', margin: 44, info: { Title: `IPDC Daily GitHub Report - ${pm.name}`, Author: 'IPDC Discord Bot' } });
  const chunks = []; doc.on('data', (d) => chunks.push(d));
  const done = new Promise((r) => doc.on('end', r));
  try { doc.image(LOGO_PATH, 44, 36, { height: 52 }); } catch (e) { log.warn('logo missing in pdf', e); }
  doc.fontSize(18).font('Helvetica-Bold').text('Daily GitHub Activity Report', 130, 44).fontSize(10).font('Helvetica')
    .text(latin(`INVICTUS PROJECT DEVELOPMENT CENTRE | ${pm.name}`), 130, 68);
  doc.moveDown(3).x = 44; doc.y = 110;
  const kv = (k, v) => doc.font('Helvetica-Bold').text(`${k}: `, { continued: true }).font('Helvetica').text(latin(v));
  kv('Repository', data.repo); kv('Period', `${fmtIST(sinceMs)} to ${fmtIST(untilMs)}`); kv('Generated', fmtIST(Date.now()));
  const commits = data.commits.filter((c) => { const t = new Date(c.date).getTime(); return t > sinceMs && t <= untilMs; });
  const pulls = data.pulls.filter((p) => new Date(p.updatedAt).getTime() > sinceMs);
  const branchesActive = new Set(commits.flatMap((c) => c.branches));
  doc.moveDown(0.5); kv('Commits', String(commits.length)); kv('Pull requests touched', String(pulls.length)); kv('Branches with activity', `${branchesActive.size} of ${data.branches.length}`);
  if (summary) { doc.moveDown(0.5).font('Helvetica-Bold').text('Summary').font('Helvetica').text(latin(summary)); }

  const h = (t) => { doc.moveDown(1).font('Helvetica-Bold').fontSize(13).text(t).fontSize(10).font('Helvetica').moveDown(0.3); };
  h('Branches');
  doc.text(latin([...branchesActive].join(', ') || 'No branch activity in this period.'));

  h('Commits by member');
  const byMember = new Map();
  for (const c of commits) { const k = c.userId || `ext:${c.authorLogin || c.authorName}`; (byMember.get(k) || byMember.set(k, []).get(k)).push(c); }
  if (!byMember.size) doc.text('No commits in this period.');
  for (const [k, list] of byMember) {
    const first = list[0]; const label = first.userId ? `${names.get(first.userId) || 'Member'} (GitHub: ${first.authorLogin})` : `${first.authorLogin || first.authorName || 'Unknown'} (not linked to a Discord member)`;
    doc.moveDown(0.4).font('Helvetica-Bold').text(latin(`${label} - ${list.length} commit(s)`)).font('Helvetica');
    for (const c of list) {
      const d = details.get(c.sha);
      const stat = d ? ` [+${d.additions}/-${d.deletions}, ${d.filesTotal} file(s)]` : '';
      if (doc.y > 760) doc.addPage();
      doc.fontSize(9).text(latin(`${fmtIST(c.date)}  ${c.sha.slice(0, 7)}  ${c.message}${stat}`), { indent: 8 })
        .fillColor('#1a5fb4').text(c.url, { indent: 8, link: c.url }).fillColor('black').fontSize(10);
    }
  }

  h('Pull request summary');
  if (!pulls.length) doc.text('No pull request activity in this period.');
  for (const p of pulls.slice(0, 40)) { if (doc.y > 760) doc.addPage(); doc.fontSize(9).text(latin(`#${p.number} [${p.state}] ${p.title} (${p.author || 'unknown'}) ${p.head}->${p.base}`), { link: p.url }); }

  doc.moveDown(1.5).fontSize(8).fillColor('#555').text('Activity counts are evidence of GitHub activity, not a definitive productivity score. Generated by the IPDC Discord Bot from GitHub data.');
  doc.end(); await done;
  return Buffer.concat(chunks);
}

export class Reports {
  constructor(ctx) { this.ctx = ctx; }

  async runAll(snaps) {
    for (const pm of await this.ctx.state.pms()) {
      const d = snaps.find((x) => x.pmId === pm.id);
      if (!d?.ok) { await this.status(pm, 'skipped', d?.error || 'no data'); continue; }
      await this.runPm(pm, d).catch((e) => log.error(`report failed for ${pm.name}`, e));
    }
  }

  async status(pm, status, error) {
    const rec = { status, error: error || null, at: Date.now() };
    await this.ctx.store.set('reportStatus', pm.id, rec);
    this.ctx.monitoring.reportStatus.set(pm.id, rec);
    await this.ctx.audit.log({ action: `report.${status}`, details: { pmId: pm.id, error } });
  }

  async runPm(pm, data, { untilMs = Date.now(), attempt = 0 } = {}) {
    const { mailer, state, ai, github } = this.ctx; const sinceMs = untilMs - DAY;
    const settings = await state.settings();
    const to = [...new Set([...(this.ctx.cfg.smtp.recipients || []), ...(settings.reportRecipients || [])])];
    const commits = data.commits.filter((c) => { const t = new Date(c.date).getTime(); return t > sinceMs && t <= untilMs; });
    const details = new Map();
    await mapLimit(commits.slice(0, 100), 4, async (c) => { try { details.set(c.sha, await github.commitDetail(pm.repo.owner, pm.repo.name, c.sha)); } catch { /* stats optional */ } });
    const names = await this.ctx.monitoring.names([...new Set(commits.map((c) => c.userId).filter(Boolean))]);
    let summary = null;
    if (commits.length) summary = (await ai.summarizeActivity({ repo: data.repo, days: 1, commits: commits.length, prs: data.pulls.length, subjects: commits.map((c) => c.message) })).text;
    const pdf = await buildPmReportPdf({ pm, data, names, details, summary, untilMs, sinceMs });
    const filename = `IPDC-${pm.slug}-${dayKeyIST(new Date(untilMs))}.pdf`;
    if (!mailer.enabled || !to.length) { await this.status(pm, 'skipped', !mailer.enabled ? 'SMTP not configured' : 'no recipients configured'); return { pdf, sent: false }; }
    try {
      await mailer.send({ to, subject: `IPDC daily GitHub report - ${pm.name} - ${dayKeyIST(new Date(untilMs))}`, text: `Attached is the consolidated daily GitHub activity report for ${pm.name}'s team (${data.repo}).\n\nActivity counts are evidence of GitHub activity, not a productivity score.`, attachments: [{ filename, content: pdf, contentType: 'application/pdf' }] });
      await this.status(pm, 'sent');
      return { pdf, sent: true };
    } catch (e) {
      await this.status(pm, 'failed', e.message);
      await this.ctx.queue.enqueue('report.retry', { pmId: pm.id, untilMs }, { delayMs: 10 * 60_000, dedupeKey: `${pm.id}_${untilMs}` });
      return { pdf, sent: false };
    }
  }

  register() {
    this.ctx.queue.register('report.retry', async ({ pmId, untilMs }) => {
      const pm = await this.ctx.state.getPm(pmId); if (!pm?.repo) return;
      const data = await this.ctx.activity.collectPm(pm);
      const r = await this.runPm(pm, data, { untilMs });
      if (!r.sent) throw new Error('report still not delivered');
    });
  }
}
